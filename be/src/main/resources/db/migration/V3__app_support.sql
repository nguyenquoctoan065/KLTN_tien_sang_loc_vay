-- PHIÊN ĐĂNG NHẬP (token ngẫu nhiên trả cho FE, DB chỉ lưu SHA-256 của token)
CREATE TABLE auth_session (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    token_hash varchar(64) NOT NULL UNIQUE,
    account_kind varchar(10) NOT NULL CHECK (account_kind IN ('CUSTOMER','STAFF')),
    account_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    CONSTRAINT pk_auth_session PRIMARY KEY (id)
);
COMMENT ON COLUMN auth_session.id IS 'Mã phiên';
COMMENT ON COLUMN auth_session.token_hash IS 'SHA-256 (hex) của token Bearer; LoginResponse.token chỉ trả một lần khi đăng nhập/đăng ký';
COMMENT ON COLUMN auth_session.account_kind IS 'Loại tài khoản: CUSTOMER (bảng customer) hoặc STAFF (bảng staff)';
COMMENT ON COLUMN auth_session.account_id IS 'Mã tài khoản trong bảng tương ứng; AuthUser.id';
COMMENT ON COLUMN auth_session.created_at IS 'Thời điểm đăng nhập';
COMMENT ON COLUMN auth_session.expires_at IS 'Hết hạn (created_at + app.session-hours)';
COMMENT ON COLUMN auth_session.revoked_at IS 'Thu hồi: đăng xuất, khóa tài khoản, đổi hoặc đặt lại mật khẩu';
COMMENT ON TABLE auth_session IS 'PHIÊN ĐĂNG NHẬP';
CREATE INDEX ix_auth_session_account ON auth_session (account_kind, account_id) WHERE revoked_at IS NULL;

-- MÃ OTP (POST /auth/otp, kiểm tra ở /auth/register và các thao tác xác nhận của khách hàng)
CREATE TABLE otp_code (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    target varchar(15) NOT NULL,
    purpose varchar(20) NOT NULL,
    code_hash varchar(64) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    attempts int NOT NULL DEFAULT 0,
    used_at timestamptz,
    CONSTRAINT pk_otp_code PRIMARY KEY (id)
);
COMMENT ON COLUMN otp_code.id IS 'Mã OTP';
COMMENT ON COLUMN otp_code.target IS 'Số điện thoại nhận mã (OtpSent, RegisterRequest.phone)';
COMMENT ON COLUMN otp_code.purpose IS 'Mục đích: REGISTER (chưa đăng nhập, đăng ký) hoặc CONFIRM (khách đang đăng nhập: nộp hồ sơ, rút đồng ý)';
COMMENT ON COLUMN otp_code.code_hash IS 'SHA-256 (hex) của target, purpose và mã; không lưu mã gốc';
COMMENT ON COLUMN otp_code.created_at IS 'Thời điểm gửi';
COMMENT ON COLUMN otp_code.expires_at IS 'Hết hạn (created_at + 5 phút)';
COMMENT ON COLUMN otp_code.attempts IS 'Số lần nhập sai; tối đa 5 thì mã không còn dùng được';
COMMENT ON COLUMN otp_code.used_at IS 'Đã dùng hoặc bị thay bằng mã mới';
COMMENT ON TABLE otp_code IS 'MÃ OTP';
CREATE INDEX ix_otp_code_target ON otp_code (target, purpose) WHERE used_at IS NULL;

-- Email khách hàng không trùng, không phân biệt hoa thường (RegisterRequest.email; 409 "Email đã được sử dụng.")
CREATE UNIQUE INDEX ux_customer_email_lower ON customer (lower(email)) WHERE email IS NOT NULL;
