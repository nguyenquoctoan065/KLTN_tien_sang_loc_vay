-- HỒ SƠ VAY: thông tin cá nhân khai theo từng hồ sơ (Application.personal, như mock lưu app.personal; phone lấy từ customer)
ALTER TABLE loan_application
    ADD COLUMN full_name varchar(100),
    ADD COLUMN national_id varchar(12),
    ADD COLUMN dob date,
    ADD COLUMN gender varchar(10) CHECK (gender IN ('MALE','FEMALE')),
    ADD COLUMN address varchar(255),
    ADD COLUMN email varchar(100),
    ADD COLUMN cancel_reason varchar(255),
    ADD COLUMN warnings jsonb NOT NULL DEFAULT '[]',
    ADD COLUMN recalc jsonb;
COMMENT ON COLUMN loan_application.full_name IS 'PersonalInfo.fullName (khai trong hồ sơ)';
COMMENT ON COLUMN loan_application.national_id IS 'PersonalInfo.nationalId – số CCCD 12 chữ số';
COMMENT ON COLUMN loan_application.dob IS 'PersonalInfo.dob (mặc định lấy từ lượt sàng lọc)';
COMMENT ON COLUMN loan_application.gender IS 'PersonalInfo.gender: MALE, FEMALE';
COMMENT ON COLUMN loan_application.address IS 'PersonalInfo.address – địa chỉ thường trú';
COMMENT ON COLUMN loan_application.email IS 'PersonalInfo.email';
COMMENT ON COLUMN loan_application.cancel_reason IS 'Lý do hủy (CancelRequest.reason)';
COMMENT ON COLUMN loan_application.warnings IS 'Application.warnings – kết quả đối chiếu MB06 ↔ MB01 lần chạy gần nhất (CrossCheckWarning[])';
COMMENT ON COLUMN loan_application.recalc IS 'Application.recalc – tính lại theo thu nhập kiểm chứng (Recalculation), rỗng nếu chưa có sao kê';

-- TÀI LIỆU: dòng MISSING được tạo sẵn khi lập hồ sơ (danh mục MB05) nên các cột về tệp được phép rỗng
ALTER TABLE application_document
    ALTER COLUMN file_name DROP NOT NULL,
    ALTER COLUMN file_format DROP NOT NULL,
    ALTER COLUMN file_size DROP NOT NULL,
    ALTER COLUMN storage_path DROP NOT NULL,
    ALTER COLUMN quality_status DROP NOT NULL,
    ALTER COLUMN uploaded_at DROP NOT NULL,
    ALTER COLUMN uploaded_at DROP DEFAULT,
    ADD COLUMN status varchar(20) NOT NULL DEFAULT 'MISSING' CHECK (status IN ('MISSING','UPLOADED','CONFIRMED','REJECTED_QUALITY')),
    ADD COLUMN required boolean NOT NULL DEFAULT true,
    ADD COLUMN quality_message varchar(255),
    ADD COLUMN storage_resource_type varchar(10),
    ADD COLUMN storage_version bigint,
    ADD COLUMN verify_result varchar(20) CHECK (verify_result IN ('MATCH','MISMATCH','MISSING')),
    ADD COLUMN verify_reason varchar(255),
    ADD CONSTRAINT ck_application_document_quality CHECK (quality_status IN ('OK','BLURRY','WRONG_FORMAT','TOO_LARGE','WRONG_TYPE'));
COMMENT ON COLUMN application_document.status IS 'AppDocument.status: MISSING, UPLOADED, CONFIRMED, REJECTED_QUALITY';
COMMENT ON COLUMN application_document.required IS 'AppDocument.required – chụp quy tắc product_document_type lúc lập hồ sơ';
COMMENT ON COLUMN application_document.quality_message IS 'AppDocument.qualityMessage – lời nhắc khi không đạt chất lượng';
COMMENT ON COLUMN application_document.storage_path IS 'public_id của tệp trong kho lưu trữ (Cloudinary hoặc thư mục cục bộ)';
COMMENT ON COLUMN application_document.storage_resource_type IS 'resource_type của tệp lưu trữ (image, raw) – để sinh URL ký (AppDocument.previewUrl)';
COMMENT ON COLUMN application_document.storage_version IS 'version của tệp lưu trữ – để sinh URL ký';
COMMENT ON COLUMN application_document.verify_result IS 'AppDocument.verifyResult – kết quả đối chiếu gần nhất tại chi nhánh; xóa khi tải lại';
COMMENT ON COLUMN application_document.verify_reason IS 'AppDocument.verifyReason';

