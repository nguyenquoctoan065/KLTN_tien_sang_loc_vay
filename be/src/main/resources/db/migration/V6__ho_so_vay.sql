-- LỊCH SỬ TRẠNG THÁI HỒ SƠ (Application.history – StatusEvent)
CREATE TABLE application_status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    application_id bigint NOT NULL,
    from_status varchar(30),
    to_status varchar(30) NOT NULL,
    actor_type varchar(20) NOT NULL CHECK (actor_type IN ('CUSTOMER','STAFF','SYSTEM')),
    actor_id bigint,
    actor_name varchar(100) NOT NULL,
    note varchar(255),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_application_status_history PRIMARY KEY (id),
    CONSTRAINT fk_application_status_history_application_id FOREIGN KEY (application_id) REFERENCES loan_application (id)
);
COMMENT ON COLUMN application_status_history.id IS 'Mã dòng lịch sử';
COMMENT ON COLUMN application_status_history.application_id IS 'Mã hồ sơ';
COMMENT ON COLUMN application_status_history.from_status IS 'Trạng thái trước (rỗng khi tạo hồ sơ)';
COMMENT ON COLUMN application_status_history.to_status IS 'StatusEvent.status – trạng thái mới';
COMMENT ON COLUMN application_status_history.actor_type IS 'Loại người thực hiện: CUSTOMER, STAFF, SYSTEM';
COMMENT ON COLUMN application_status_history.actor_id IS 'Mã người thực hiện';
COMMENT ON COLUMN application_status_history.actor_name IS 'StatusEvent.actor – tên người thực hiện tại thời điểm chuyển';
COMMENT ON COLUMN application_status_history.note IS 'StatusEvent.note';
COMMENT ON COLUMN application_status_history.created_at IS 'StatusEvent.at';
COMMENT ON TABLE application_status_history IS 'LỊCH SỬ TRẠNG THÁI HỒ SƠ';
CREATE INDEX ix_status_history_application ON application_status_history (application_id, id);

-- THÔNG BÁO TRONG ỨNG DỤNG (AppNotification; người nhận là một khách hàng hoặc một chi nhánh)
CREATE TABLE notification (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    customer_id bigint,
    branch_id int,
    title varchar(150) NOT NULL,
    body varchar(500) NOT NULL,
    link varchar(255),
    created_at timestamptz NOT NULL DEFAULT now(),
    read_at timestamptz,
    CONSTRAINT pk_notification PRIMARY KEY (id),
    CONSTRAINT fk_notification_customer_id FOREIGN KEY (customer_id) REFERENCES customer (id),
    CONSTRAINT fk_notification_branch_id FOREIGN KEY (branch_id) REFERENCES branch (id),
    CONSTRAINT ck_notification_target CHECK (customer_id IS NOT NULL OR branch_id IS NOT NULL)
);
COMMENT ON COLUMN notification.id IS 'AppNotification.id';
COMMENT ON COLUMN notification.customer_id IS 'Khách hàng nhận (rỗng nếu gửi chi nhánh)';
COMMENT ON COLUMN notification.branch_id IS 'Chi nhánh nhận – mọi nhân viên của chi nhánh cùng thấy';
COMMENT ON COLUMN notification.title IS 'AppNotification.title';
COMMENT ON COLUMN notification.body IS 'AppNotification.body';
COMMENT ON COLUMN notification.link IS 'AppNotification.link – đường dẫn frontend dùng mã công khai của hồ sơ';
COMMENT ON COLUMN notification.created_at IS 'AppNotification.createdAt';
COMMENT ON COLUMN notification.read_at IS 'Thời điểm đánh dấu đã đọc (AppNotification.read = read_at khác rỗng)';
COMMENT ON TABLE notification IS 'THÔNG BÁO';
CREATE INDEX ix_notification_customer ON notification (customer_id, id) WHERE customer_id IS NOT NULL;
CREATE INDEX ix_notification_branch ON notification (branch_id, id) WHERE customer_id IS NULL;
