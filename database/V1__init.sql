-- KHÁCH HÀNG
CREATE TABLE customer (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    phone varchar(15) NOT NULL UNIQUE,
    email varchar(100),
    password_hash varchar(255) NOT NULL,
    full_name varchar(100),
    national_id varchar(12),
    dob date,
    gender varchar(10),
    address varchar(255),
    status varchar(20) NOT NULL CHECK (status IN ('ACTIVE','LOCKED','DELETED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_customer PRIMARY KEY (id)
);
COMMENT ON COLUMN customer.id IS 'Mã khách hàng';
COMMENT ON COLUMN customer.phone IS 'Số điện thoại đăng nhập';
COMMENT ON COLUMN customer.email IS 'Email';
COMMENT ON COLUMN customer.password_hash IS 'Mật khẩu đã băm';
COMMENT ON COLUMN customer.full_name IS 'Họ tên';
COMMENT ON COLUMN customer.national_id IS 'Số CCCD';
COMMENT ON COLUMN customer.dob IS 'Ngày sinh';
COMMENT ON COLUMN customer.gender IS 'Giới tính';
COMMENT ON COLUMN customer.address IS 'Địa chỉ';
COMMENT ON COLUMN customer.status IS 'Trạng thái tài khoản';
COMMENT ON COLUMN customer.created_at IS 'Ngày đăng ký';
COMMENT ON TABLE customer IS 'KHÁCH HÀNG';

